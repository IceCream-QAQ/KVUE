package kvue.codegen

import com.squareup.kotlinpoet.ANY
import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.Dynamic
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LambdaTypeName
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeName
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.UNIT

object ComponentCodegen {
    fun generate(model: ComponentModel, declarationsOnly: Boolean = false): List<FileSpec> {
        require(model.bindingNameConflicts().isEmpty()) { "Conflicting binding parameter names: ${model.bindingNameConflicts()}" }
        require(model.exposedNameConflicts().isEmpty()) { "Conflicting exposed member names: ${model.exposedNameConflicts()}" }
        val bindings = model.bindings
        val files = mutableListOf<FileSpec>()
        val visibility = model.visibility
        val definition = if (declarationsOnly) CodeBlock.of("error(%S)", "IDE declaration only")
            else if (model.jsImport != null) importedDefinition(model, files) else nativeDefinition(model)

        val backingObject = TypeSpec.objectBuilder(model.generatedName)
            .addModifiers(visibility)
            .addProperty(
                PropertySpec.builder("definition", if (model.jsImport != null) JS_DEFINITION else DEFINITION.parameterizedBy(model.className))
                    .initializer(definition)
                    .build()
            )
        if (model.hasInstance) backingObject.addFunction(FunSpec.builder("ref").addModifiers(visibility)
            .returns(COMPONENT_REF.parameterizedBy(model.instanceName))
            .addStatement(if (declarationsOnly) "error(%S)" else "return %T(::%T)",
                *if (declarationsOnly) arrayOf("IDE declaration only") else arrayOf(COMPONENT_REF, model.instanceName))
            .build())
        val nodeType = nodeType(model, declarationsOnly)
        val contentTypes = contentTypes(model, declarationsOnly)
        backingObject.addTypes(contentTypes)
        val instanceType = model.takeIf { it.hasInstance }?.let { instanceType(it, declarationsOnly) }

        val dsl = FunSpec.builder(model.className.simpleName)
            .addModifiers(visibility)
            .receiver(RENDER_GROUP)
            .returns(model.nodeName)
        model.props.forEach { prop ->
            val type = when {
                prop.required -> prop.type
                prop.nullable -> OPTIONAL_PROP.parameterizedBy(prop.type)
                else -> prop.type.copy(nullable = true)
            }
            val parameter = ParameterSpec.builder(prop.name, type)
            if (prop.required && bindings.any { it.prop == prop }) {
                parameter.addAnnotation(REQUIRED_BINDING_PROP)
                parameter.defaultValue("%M(%S)", REQUIRED_PROP_DEFAULT, prop.name)
            }
            if (!prop.required) {
                if (prop.nullable) parameter.defaultValue("%T.Omitted", OPTIONAL_PROP)
                else parameter.defaultValue("null")
            }
            dsl.addParameter(parameter.build())
        }
        model.events.forEach { event ->
            val callbackType = LambdaTypeName.get(
                parameters = event.arguments.map { ParameterSpec.unnamed(it) },
                returnType = UNIT,
            ).copy(nullable = true)
            dsl.addParameter(ParameterSpec.builder(event.parameterName, callbackType).defaultValue("null").build())
        }
        bindings.forEach { binding ->
            binding.parameterNames.forEach { name ->
                dsl.addParameter(ParameterSpec.builder(name, binding.prop.type)
                    .addAnnotation(AnnotationSpec.builder(V_BIND)
                        .addMember("prop = %S, event = %S, variadic = %L", binding.prop.name, binding.event.parameterName, binding.event.variadic).build())
                    .defaultValue("%M()", OMITTED_BINDING)
                    .build())
            }
        }
        dsl.addParameter(ParameterSpec.builder("key", ANY.copy(nullable = true)).defaultValue("null").build())
        dsl.addParameter(ParameterSpec.builder("content", COMPONENT_CONTENT.parameterizedBy(model.contentName).copy(nullable = true))
            .defaultValue("null").build())

        if (declarationsOnly) {
            return listOf(FileSpec.builder(model.className.packageName, model.fileName)
                .addFileComment("Virtual KVUE declarations. Build implementations are generated by KSP.")
                .addType(backingObject.build())
                .addType(nodeType)
                .apply { instanceType?.let { addType(it) } }
                .addFunction(dsl.addStatement("error(%S)", "IDE declaration only").build())
                .build())
        }
        val usedNames = model.props.map { it.name } + model.events.map { it.parameterName } + bindings.flatMap { it.parameterNames } + listOf("key", "content")
        val node = generateSequence("node") { it + "_" }.first { it !in usedNames }
        if (bindings.isNotEmpty()) {
            val checks = CodeBlock.builder()
            bindings.flatMap { it.parameterNames }.forEachIndexed { index, name ->
                if (index > 0) checks.add(", ")
                checks.add("%N", name)
            }
            dsl.addStatement("%M(%L)", CHECK_BINDINGS, checks.build())
        }
        dsl.addStatement("val %N = %T()", node, model.nodeName)
        model.props.forEach { prop ->
            val value = if (prop.required || !prop.nullable) CodeBlock.of("%N", prop.name) else CodeBlock.of("%N.value", prop.name)
            val forwarded = if (prop.variadic) CodeBlock.of("%M(%L)", VARIADIC_CALLBACK, value) else value
            when {
                prop.required -> dsl.addStatement("%N.property(%S, %L)", node, prop.wireName, forwarded)
                prop.nullable -> {
                    dsl.beginControlFlow("if (%N is %T.Value<*>)", prop.name, OPTIONAL_PROP)
                        .addStatement("%N.property(%S, %L)", node, prop.wireName, forwarded)
                        .endControlFlow()
                }
                else -> {
                    dsl.beginControlFlow("if (%N != null)", prop.name)
                        .addStatement("%N.property(%S, %L)", node, prop.wireName, forwarded)
                        .endControlFlow()
                }
            }
        }
        model.events.forEach { event ->
            val value = if (event.variadic) CodeBlock.of("%M(%N)", VARIADIC_CALLBACK, event.parameterName) else CodeBlock.of("%N", event.parameterName)
            dsl.beginControlFlow("if (%N != null)", event.parameterName)
                .addStatement("%N.listener(%S, %L)", node, event.listenerName, value)
                .endControlFlow()
        }
        dsl.beginControlFlow("if (key != null)").addStatement("%N.property(%S, key)", node, "key").endControlFlow()
        dsl.addStatement("%M(%N, content) { %T() }", BIND_COMPONENT_CONTENT, node, model.contentName)
        dsl.addStatement("this.addElement(%N)", node).addStatement("return %N", node)

        val file = FileSpec.builder(model.className.packageName, model.className.simpleName + "KVueGenerated")
            .addFileComment("Generated by KVUE KSP. Do not edit.")
            .addType(backingObject.build())
            .addType(nodeType)
            .apply { instanceType?.let { addType(it) } }
            .addFunction(dsl.build())
            .build()
        files += file
        return files
    }

    private fun nodeType(model: ComponentModel, declarationsOnly: Boolean): TypeSpec {
        val builder = TypeSpec.classBuilder(model.nodeName).addModifiers(model.visibility)
            .primaryConstructor(FunSpec.constructorBuilder().addModifiers(KModifier.INTERNAL).build())
            .superclass(ELEMENT_NODE).addSuperclassConstructorParameter("%T.definition", model.generatedName)
        builder.addFunction(FunSpec.builder("slot").addModifiers(KModifier.OVERRIDE)
            .addParameter("name", STRING).addParameter("renderFun", RENDER_FUN).returns(model.nodeName)
            .apply {
                if (declarationsOnly) addStatement("error(%S)", "IDE declaration only")
                else { addStatement("super.slot(name, renderFun)"); addStatement("return this") }
            }.build())
        for (event in model.events) {
            val function = FunSpec.builder(event.parameterName).returns(model.nodeName)
                .addParameter("handler", LambdaTypeName.get(parameters = event.arguments.map { ParameterSpec.unnamed(it) }, returnType = UNIT))
            if (declarationsOnly) function.addStatement("error(%S)", "IDE declaration only")
            else {
                val callback = if (event.variadic) CodeBlock.of("%M(handler)", VARIADIC_CALLBACK) else CodeBlock.of("handler")
                function.addStatement("listener(%S, %L)", event.listenerName, callback).addStatement("return this")
            }
            builder.addFunction(function.build())
        }
        if (model.hasInstance) {
            val function = FunSpec.builder("ref").returns(model.nodeName)
                .addParameter("target", COMPONENT_REF.parameterizedBy(model.instanceName))
            if (declarationsOnly) function.addStatement("error(%S)", "IDE declaration only")
            else function.addStatement("componentRef(target)").addStatement("return this")
            builder.addFunction(function.build())
        }
        return builder.build()
    }

    private fun contentTypes(model: ComponentModel, declarationsOnly: Boolean): List<TypeSpec> {
        val scope = TypeSpec.classBuilder(model.contentName).addModifiers(model.visibility)
            .primaryConstructor(FunSpec.constructorBuilder().addModifiers(KModifier.INTERNAL).build())
            .superclass(COMPONENT_CONTENT_SCOPE)
            .addProperty(PropertySpec.builder("slots", model.slotsName)
                .initializer(if (declarationsOnly) CodeBlock.of("error(%S)", "IDE declaration only")
                    else CodeBlock.of("%T(this)", model.slotsName)).build())
            .build()
        val slots = TypeSpec.classBuilder(model.slotsName).addModifiers(model.visibility)
            .primaryConstructor(FunSpec.constructorBuilder().addModifiers(KModifier.INTERNAL)
                .addParameter("scope", COMPONENT_CONTENT_SCOPE).build())
            .addProperty(PropertySpec.builder("scope", COMPONENT_CONTENT_SCOPE, KModifier.PRIVATE).initializer("scope").build())
        model.slotMembers.forEach { (wire, member) ->
            slots.addFunction(FunSpec.builder(member)
                .addAnnotation(AnnotationSpec.builder(SLOT_DECLARATION).addMember("name = %S", wire).build())
                .addParameter("content", RENDER_FUN)
                .apply {
                    if (declarationsOnly) addStatement("error(%S)", "IDE declaration only")
                    else addStatement("scope.slot(%S, content)", wire)
                }.build())
        }
        return listOf(scope, slots.build())
    }

    private fun instanceType(model: ComponentModel, declarationsOnly: Boolean): TypeSpec {
        val builder = TypeSpec.classBuilder(model.instanceName).addModifiers(model.visibility)
            .primaryConstructor(FunSpec.constructorBuilder().addModifiers(KModifier.INTERNAL)
                .addParameter("instance", ANY.copy(nullable = true)).build())
            .superclass(COMPONENT_INSTANCE).addSuperclassConstructorParameter("instance")
        for (method in model.methods) {
            val function = FunSpec.builder(method.name).returns(method.returnType)
            method.parameters.forEach { argument ->
                val parameter = ParameterSpec.builder(argument.name,
                    if (argument.optional) OPTIONAL_PROP.parameterizedBy(argument.type) else argument.type)
                if (argument.optional) parameter.defaultValue("%T.Omitted", OPTIONAL_PROP)
                function.addParameter(parameter.build())
            }
            if (declarationsOnly) function.addStatement("error(%S)", "IDE declaration only")
            else {
                val arguments = if (method.variadic) CodeBlock.of("%N", method.parameters.single().name) else
                    CodeBlock.builder().add("arrayOf(").apply {
                        method.parameters.forEachIndexed { index, parameter ->
                            if (index > 0) add(", ")
                            add("%N", parameter.name)
                        }
                    }.add(")").build()
                val call = CodeBlock.of("this.invokeExposed(%S, %L)", method.wireName, arguments)
                if (method.returnType == UNIT) function.addStatement("%L", call)
                else function.addStatement("return %L.unsafeCast<%T>()", call, method.returnType)
            }
            builder.addFunction(function.build())
        }
        model.exposedProperties.forEach { property ->
            val getter = FunSpec.getterBuilder()
            if (declarationsOnly) getter.addStatement("error(%S)", "IDE declaration only")
            else getter.addStatement("return readExposed(%S).unsafeCast<%T>()", property.wireName, property.type)
            val generated = PropertySpec.builder(property.name, property.type).mutable(property.mutable).getter(getter.build())
            if (property.mutable) {
                val setter = FunSpec.setterBuilder().addParameter("value", property.type)
                if (declarationsOnly) setter.addStatement("error(%S)", "IDE declaration only")
                else setter.addStatement("writeExposed(%S, value)", property.wireName)
                generated.setter(setter.build())
            }
            builder.addProperty(generated.build())
        }
        return builder.build()
    }

    private fun importedDefinition(model: ComponentModel, files: MutableList<FileSpec>): CodeBlock {
        val jsImport = checkNotNull(model.jsImport)
        val importsPackage = listOf(model.className.packageName, "imports").filter { it.isNotEmpty() }.joinToString(".")
        val rawName = "raw" + model.className.simpleName
        val file = FileSpec.builder(importsPackage, model.className.simpleName + "JsImport")
        val raw = PropertySpec.builder(rawName, Dynamic).addModifiers(KModifier.INTERNAL, KModifier.EXTERNAL)
        if (jsImport.exportName == "default" || jsImport.exportName == "export=") {
            raw.addAnnotation(AnnotationSpec.builder(JS_MODULE).addMember("%S", jsImport.module).build())
            raw.addAnnotation(JS_NON_MODULE)
        } else {
            file.addAnnotation(AnnotationSpec.builder(JS_MODULE).useSiteTarget(AnnotationSpec.UseSiteTarget.FILE).addMember("%S", jsImport.module).build())
            file.addAnnotation(AnnotationSpec.builder(JS_NON_MODULE).useSiteTarget(AnnotationSpec.UseSiteTarget.FILE).build())
            raw.addAnnotation(AnnotationSpec.builder(JS_NAME).addMember("%S", jsImport.exportName).build())
        }
        file.addProperty(raw.build())
        files += file.build()
        val imported = CodeBlock.of("%M", MemberName(importsPackage, rawName))
        val value = if (jsImport.exportName == "default") CodeBlock.of("%M(%L)", DEFAULT_EXPORT, imported) else imported
        return CodeBlock.of("%T(%L, %S)", JS_DEFINITION, value, "${jsImport.module}:${jsImport.exportName}")
    }

    private fun nativeDefinition(model: ComponentModel): CodeBlock {
        val definition = CodeBlock.builder()
            .add("%T(\n", DEFINITION)
            .indent()
            .add("name = %S,\n", model.className.simpleName)
            .add("props = arrayOf(")
        model.props.forEachIndexed { index, prop ->
            if (index > 0) definition.add(", ")
            definition.add("%T(%S, required = %L, propertyName = %S)", COMPONENT_PROP, prop.wireName, prop.required, prop.name)
        }
        definition.add("),\nemits = arrayOf(")
        model.events.forEachIndexed { index, event ->
            if (index > 0) definition.add(", ")
            definition.add("%S", event.eventName)
        }
        definition.add("),\nfactory = { %T() },\n", model.className)
        if (model.events.isNotEmpty()) {
            definition.add("bindEvents = { context ->\n").indent()
            model.events.forEachIndexed { eventIndex, event ->
                val functionType = LambdaTypeName.get(
                    parameters = event.arguments.map { ParameterSpec.unnamed(it) },
                    returnType = UNIT,
                )
                definition.add("val event%L: %T = { ", eventIndex, functionType)
                if (event.arguments.isNotEmpty()) {
                    event.arguments.forEachIndexed { index, type ->
                        if (index > 0) definition.add(", ")
                        definition.add("arg%L: %T", index, type)
                    }
                    definition.add(" -> ")
                }
                definition.add("context.emit(%S", event.eventName)
                event.arguments.indices.forEach { definition.add(", arg%L", it) }
                definition.add(") }\n")
            }
            definition.add("mapOf<String, Any>(\n").indent()
            model.events.forEachIndexed { index, event ->
                definition.add("%S to event%L,\n", event.propertyName, index)
            }
            definition.unindent().add(")\n").unindent().add("},\n")
        }
        definition.add("expose = { instance ->\n").indent().add("val exposed = %M()\n", JSO)
        model.methods.forEach { method ->
            definition.add("exposed[%S] = { ", method.wireName)
            method.parameters.forEachIndexed { index, parameter ->
                if (index > 0) definition.add(", ")
                definition.add("arg%L: %T", index, parameter.type)
            }
            if (method.parameters.isNotEmpty()) definition.add(" -> ")
            definition.add("instance.%N(", method.name)
            method.parameters.forEachIndexed { index, parameter ->
                if (index > 0) definition.add(", ")
                definition.add("arg%L", index)
            }
            definition.add(") }\n")
        }
        model.exposedProperties.forEach { property ->
            definition.add("%M(exposed, %S, { instance.%N }", DEFINE_EXPOSED_PROPERTY, property.wireName, property.name)
            if (property.mutable) definition.add(", { value -> instance.%N = value.unsafeCast<%T>() }", property.name, property.type)
            definition.add(")\n")
        }
        definition.add("exposed\n").unindent().add("},\n")
        definition.unindent().add(")")
        return definition.build()
    }

}

private val DEFINITION = ClassName("kvue", "ComponentDefinition")
private val COMPONENT_PROP = ClassName("kvue", "ComponentProp")
private val COMPONENT_REF = ClassName("kvue", "ComponentRef")
private val COMPONENT_INSTANCE = ClassName("kvue", "ComponentInstance")
private val JSO = MemberName("kvue.fun", "jso")
private val DEFINE_EXPOSED_PROPERTY = MemberName("kvue", "defineExposedProperty")
private val OPTIONAL_PROP = ClassName("kvue", "OptionalProp")
private val RENDER_GROUP = ClassName("kvue.vdom", "RenderGroup")
private val RENDER_FUN = ClassName("kvue.vdom", "RenderFun")
private val STRING = ClassName("kotlin", "String")
private val COMPONENT_CONTENT = ClassName("kvue.vdom", "ComponentContent")
private val COMPONENT_CONTENT_SCOPE = ClassName("kvue.vdom", "ComponentContentScope")
private val BIND_COMPONENT_CONTENT = MemberName("kvue.vdom", "bindComponentContent")
private val SLOT_DECLARATION = ClassName("kvue.annotation", "SlotDeclaration")
private val ELEMENT_NODE = ClassName("kvue.vdom.knode", "ElementNode")
private val JS_DEFINITION = ClassName("kvue", "JsComponentDefinition")
private val JS_MODULE = ClassName("kotlin.js", "JsModule")
private val JS_NON_MODULE = ClassName("kotlin.js", "JsNonModule")
private val JS_NAME = ClassName("kotlin.js", "JsName")
private val DEFAULT_EXPORT = MemberName("kvue", "jsDefaultExport")
private val VARIADIC_CALLBACK = MemberName("kvue", "variadicJsCallback")
private val V_BIND = ClassName("kvue.annotation", "VBind")
private val REQUIRED_BINDING_PROP = ClassName("kvue.annotation", "RequiredBindingProp")
private val OMITTED_BINDING = MemberName("kvue", "omittedBinding")
private val CHECK_BINDINGS = MemberName("kvue", "checkBindingArguments")
private val REQUIRED_PROP_DEFAULT = MemberName("kvue", "requiredBindingProp")
